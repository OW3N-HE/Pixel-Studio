inline bool hostUsesChinese() {
    // OpenRGB translates this language name using its active application translator.
    // Inspecting that translator also honors explicit host-language overrides.
    const auto name = QCoreApplication::translate("Ui::OpenRGBSettingsPage", "English - US");
    return name.contains(QStringLiteral("Chinese"), Qt::CaseInsensitive)
        || name.contains(QString::fromUtf8("中文")) || name.contains(QString::fromUtf8("简体"))
        || name.contains(QString::fromUtf8("繁體")) || name.contains(QString::fromUtf8("汉语"))
        || name.contains(QString::fromUtf8("漢語"));
}
